/**
 * Writes build-time provenance constants (commit SHA + timestamp).
 * No secrets. Prefer VERCEL_GIT_COMMIT_SHA when present.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(
  root,
  "src",
  "lib",
  "generated",
  "build-provenance.generated.ts",
);

function resolveCommitSha() {
  const fromEnv =
    process.env.VERCEL_GIT_COMMIT_SHA ||
    process.env.GIT_COMMIT_SHA ||
    process.env.GITHUB_SHA ||
    "";
  if (fromEnv.trim()) return fromEnv.trim();
  try {
    return execSync("git rev-parse HEAD", {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "unknown";
  }
}

const commitSha = resolveCommitSha();
const builtAt = new Date().toISOString();

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `/** AUTO-GENERATED by scripts/write-build-provenance.mjs — do not edit. */
export const BUILD_PROVENANCE_EMBEDDED = {
  commitSha: ${JSON.stringify(commitSha)},
  builtAt: ${JSON.stringify(builtAt)},
} as const;
`,
  "utf8",
);

console.log(
  JSON.stringify({
    wrote: "src/lib/generated/build-provenance.generated.ts",
    commitSha,
    builtAt,
  }),
);
